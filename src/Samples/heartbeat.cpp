    HeartbeatBypass::HeartbeatBypass(LogFn log)
        : m_log(std::move(log))
    {
    }

    void HeartbeatBypass::Log(const wchar_t* fmt, ...) const
    {
        if (!m_log) return;
        wchar_t buf[1024] = {};
        va_list args;
        va_start(args, fmt);
        _vsnwprintf_s(buf, _countof(buf), _TRUNCATE, fmt, args);
        va_end(args);
        m_log(buf);
    }

    bool HeartbeatBypass::ValidatePE(uintptr_t base)
    {
        // No C++ objects in scope — __try is safe here.
        if (!base) return false;
        __try
        {
            const auto* dos = reinterpret_cast<PIMAGE_DOS_HEADER>(base);
            if (dos->e_magic != IMAGE_DOS_SIGNATURE) return false;
            const auto* nt = reinterpret_cast<PIMAGE_NT_HEADERS32>(base + dos->e_lfanew);
            if (nt->Signature != IMAGE_NT_SIGNATURE) return false;
            if (nt->OptionalHeader.Magic != IMAGE_NT_OPTIONAL_HDR32_MAGIC) return false;
            return true;
        }
        __except (EXCEPTION_EXECUTE_HANDLER)
        {
            return false;
        }
    }

    uintptr_t HeartbeatBypass::WaitForX3(DWORD timeoutMs)
    {
        const DWORD step = 200;
        DWORD elapsed = 0;

        while (elapsed < timeoutMs)
        {
            HMODULE hMod = GetModuleHandleW(X3::MODULE_NAME);
            if (hMod)
            {
                uintptr_t base = reinterpret_cast<uintptr_t>(hMod);
                if (ValidatePE(base))
                {
                    Log(L"[HB] x3.xem bulundu: base=0x%p (%lu ms icinde)", (void*)base, elapsed);
                    return base;
                }
            }
            Sleep(step);
            elapsed += step;
        }

        Log(L"[HB] HATA: x3.xem %lu ms icinde bulunamadi!", timeoutMs);
        return 0;
    }

    PatchRecord HeartbeatBypass::PatchHandler(uintptr_t base, uint32_t rva, const char* name,
                                               const uint8_t* patchBytes, size_t patchLen)
    {
        PatchRecord rec = {};
        rec.name    = name;
        rec.address = base + rva;
        rec.patchLen = patchLen;

        auto* addr = reinterpret_cast<uint8_t*>(rec.address);

        if (!SafeReadBytes(addr, rec.original, patchLen))
        {
            rec.success = false;
            rec.detail  = "ReadFault: cannot read original bytes";
            return rec;
        }

        DWORD oldProt = 0;
        if (!VirtualProtect(addr, patchLen, PAGE_EXECUTE_READWRITE, &oldProt))
        {
            rec.success = false;
            rec.detail  = "VirtualProtect(RWX) failed: err=" + std::to_string(GetLastError());
            return rec;
        }

        if (!SafeWriteBytes(addr, patchBytes, patchLen))
        {
            VirtualProtect(addr, patchLen, oldProt, &oldProt);
            rec.success = false;
            rec.detail  = "WriteFault: patch write failed";
            return rec;
        }

        DWORD dummy = 0;
        VirtualProtect(addr, patchLen, oldProt, &dummy);
        FlushInstructionCache(GetCurrentProcess(), addr, patchLen);

        rec.success = true;
        rec.detail  = "patched ok";
        return rec;
    }

    std::vector<PatchRecord> HeartbeatBypass::Install()
    {
        m_patches.clear();
        m_installed = false;

        Log(L"[HB] ================================================");
        Log(L"[HB] XignCode3 Heartbeat Bypass baslatiliyor...");
        Log(L"[HB] Hedef: x3.xem validation handler'lari patch edilecek");
        Log(L"[HB] ================================================");

        // We inject AFTER xhunter2 loads, so x3.xem should already be in memory.
        uintptr_t base = WaitForX3(3000);
        if (!base)
        {
            Log(L"[HB] HATA: x3.xem bulunamadi. Bypass iptal.");
            return m_patches;
        }

        const auto* dos = reinterpret_cast<PIMAGE_DOS_HEADER>(base);
        const auto* nt  = reinterpret_cast<PIMAGE_NT_HEADERS32>(base + dos->e_lfanew);
        uint32_t origBase    = nt->OptionalHeader.ImageBase;
        uint32_t sizeOfImage = nt->OptionalHeader.SizeOfImage;

        Log(L"[HB] x3.xem -> LoadBase=0x%08X | OrigBase=0x%08X | Size=0x%X",
            (uint32_t)base, origBase, sizeOfImage);

        // --- 1. Patch static dispatch handlers (correct RET per arg count) ---
        // RVA dogrulama: hedef RVA'daki ilk byte bir fonksiyon baslangici olmali.
        // Beklenen: PUSH EBP (0x55) veya PUSH ESI (0x56) veya MOV EDI,EDI (0x8B,0xFF)
        // Bu kontrol yanlis RVA patch'inden kaynaklanan crash'i onler.
        auto IsValidFunctionStart = [&](uintptr_t addr) -> bool {
            uint8_t firstBytes[4] = {};
            if (!SafeReadBytes(reinterpret_cast<const void*>(addr), firstBytes, 4)) return false;
            // Gecerli x86 function prologue'lari
            if (firstBytes[0] == 0x55) return true;              // PUSH EBP
            if (firstBytes[0] == 0x56) return true;              // PUSH ESI
            if (firstBytes[0] == 0x57) return true;              // PUSH EDI
            if (firstBytes[0] == 0x53) return true;              // PUSH EBX
            if (firstBytes[0] == 0x8B && firstBytes[1] == 0xFF) return true; // MOV EDI,EDI (hot-patch)
            if (firstBytes[0] == 0x83 && firstBytes[1] == 0xEC) return true; // SUB ESP,N
            if (firstBytes[0] == 0xB8) return true;              // MOV EAX (zaten patched)
            if (firstBytes[0] == 0xCC) return true;              // INT3 (debug break - skip)
            // Bilinen patch byte'i (zaten patched onceki run'dan)
            if (firstBytes[0] == 0xB8 && firstBytes[1] == 0x01) return true;
            return false;
        };

        int successCount = 0;
        for (const auto& tgt : X3::TARGETS)
        {
            if (tgt.rva >= sizeOfImage)
            {
                PatchRecord rec;
                rec.name    = tgt.name;
                rec.address = base + tgt.rva;
                rec.success = false;
                rec.detail  = "RVA out of image bounds";
                m_patches.push_back(rec);
                Log(L"[HB]   [SKIP] %-36S RVA=0x%04X -> image size asimi", tgt.name, tgt.rva);
                continue;
            }

            uintptr_t targetAddr = base + tgt.rva;
            if (!IsValidFunctionStart(targetAddr))
            {
                uint8_t chk[4] = {};
                SafeReadBytes(reinterpret_cast<const void*>(targetAddr), chk, 4);
                PatchRecord rec;
                rec.name    = tgt.name;
                rec.address = targetAddr;
                rec.success = false;
                rec.detail  = "Unexpected bytes at RVA (x3.xem version mismatch?) bytes="
                              + std::to_string(chk[0]) + "," + std::to_string(chk[1])
                              + "," + std::to_string(chk[2]) + "," + std::to_string(chk[3]);
                m_patches.push_back(rec);
                Log(L"[HB]   [SKIP] %-36S RVA=0x%04X bytes=%02X %02X %02X %02X -> gecersiz prolog",
                    tgt.name, tgt.rva, chk[0], chk[1], chk[2], chk[3]);
                continue;
            }

            uint8_t patch[8] = {};
            MakePatch(tgt.argBytes, patch);
            auto rec = PatchHandler(base, tgt.rva, tgt.name, patch, kPatchLen);
            m_patches.push_back(rec);

            if (rec.success)
            {
                ++successCount;
                Log(L"[HB]   [OK]   %-36S @0x%p  RET %d", tgt.name, (void*)rec.address, tgt.argBytes);
            }
            else
            {
                Log(L"[HB]   [FAIL] %-36S @0x%p -> %S", tgt.name, (void*)rec.address, rec.detail.c_str());
            }
        }

        // --- 2. Patch Ordinal4 vtable-fallback (neutralise all unhandled dispatch IDs) ---
        // At RVA 0x170C: MOV EAX,[ECX]; PUSH ESI; PUSH [EBP+8]; PUSH ECX; CALL [EAX+1C]; POP ESI; POP EBP; RET 8
        // Replace with:  XOR EAX,EAX; POP ESI; POP EBP; RET 8; NOP
        if (X3::ORDINAL4_VTBL_FALLBACK_RVA < sizeOfImage)
        {
            uintptr_t vtblAddr = base + X3::ORDINAL4_VTBL_FALLBACK_RVA;
            uint8_t chk[4] = {};
            SafeReadBytes(reinterpret_cast<const void*>(vtblAddr), chk, 4);
            // Beklenen: 8B 01 (MOV EAX,[ECX]) veya 31 C0 (XOR EAX,EAX = zaten patched)
            bool vtblOk = (chk[0] == 0x8B && chk[1] == 0x01) ||  // MOV EAX,[ECX]
                          (chk[0] == 0x31 && chk[1] == 0xC0);     // XOR EAX,EAX (zaten patched)
            if (vtblOk)
            {
                constexpr uint8_t kVtblFallback[8] = { 0x31,0xC0, 0x5E, 0x5D, 0xC2,0x08,0x00, 0x90 };
                auto rec = PatchHandler(base, X3::ORDINAL4_VTBL_FALLBACK_RVA,
                                        "Ordinal4_VtblFallback", kVtblFallback, 8);
                m_patches.push_back(rec);
                if (rec.success)
                {
                    ++successCount;
                    Log(L"[HB]   [OK]   Ordinal4 vtable-fallback patched @0x%p", (void*)rec.address);
                }
                else
                {
                    Log(L"[HB]   [FAIL] Ordinal4 vtable-fallback -> %S", rec.detail.c_str());
                }
            }
            else
            {
                Log(L"[HB]   [SKIP] Ordinal4 vtable-fallback: beklenmeyen bytes %02X %02X %02X %02X (RVA degismis?)",
                    chk[0], chk[1], chk[2], chk[3]);
            }
        }

        // --- 3. Poll g_pCoreInterface, then redirect vtable[7] to our stub ---
        {
            Log(L"[HB] g_pCoreInterface bekleniyor (maks. 5 sn)...");

            // Validate RVA range before reading
            if (X3::CORE_PTR_RVA + sizeof(uintptr_t) > sizeOfImage)
            {
                Log(L"[HB]   [SKIP] CORE_PTR_RVA=0x%X image sinirlari disinda (size=0x%X) — vtable[7] atlaniyor.",
                    X3::CORE_PTR_RVA, sizeOfImage);
            }
            else
            {
                volatile uintptr_t* pCorePtr =
                    reinterpret_cast<volatile uintptr_t*>(base + X3::CORE_PTR_RVA);
                uintptr_t coreObj = 0;
                bool readOk = false;
                for (int w = 0; w < 100; ++w)
                {
                    // SafeReadBytes: her okuma AV ile korunuyor
                    if (!SafeReadBytes(const_cast<const uintptr_t*>(pCorePtr), reinterpret_cast<uint8_t*>(&coreObj), sizeof(coreObj)))
                    {
                        Log(L"[HB]   [WARN] pCorePtr okuma AV (RVA=0x%X) — vtable[7] atlaniyor.", X3::CORE_PTR_RVA);
                        readOk = false;
                        break;
                    }
                    readOk = true;
                    if (coreObj) break;
                    Sleep(50);
                }

                if (!readOk || !coreObj)
                {
                    Log(L"[HB]   [WARN] g_pCoreInterface NULL kaldi (readOk=%d) — vtable[7] patch atlaniyor.", (int)readOk);
                }
                else
                {
                    Log(L"[HB]   g_pCoreInterface=0x%p, vtable okunuyor...", (void*)coreObj);

                    // coreObj -> vtable pointer -> vtable[7] at offset 0x1C
                    uintptr_t vtable = 0;
                    if (!SafeReadBytes(reinterpret_cast<const void*>(coreObj),
                                       reinterpret_cast<uint8_t*>(&vtable), sizeof(vtable)))
                    {
                        Log(L"[HB]   [FAIL] coreObj vtable okuma AV (coreObj=0x%p) — versiyon uyumsuzlugu?", (void*)coreObj);
                    }
                    else if (!vtable)
                    {
                        Log(L"[HB]   [WARN] vtable NULL — vtable[7] patch atlaniyor.");
                    }
                    else
                    {
                        uintptr_t* pGetProc = reinterpret_cast<uintptr_t*>(vtable + 0x1C);

                        // vtable[7] adresini oku (dogrulama icin)
                        uintptr_t origFn = 0;
                        if (!SafeReadBytes(pGetProc, reinterpret_cast<uint8_t*>(&origFn), sizeof(origFn)))
                        {
                            Log(L"[HB]   [FAIL] vtable[7] okuma AV (vtable=0x%p+0x1C) — patch atlaniyor.", (void*)vtable);
                        }
                        else
                        {
                            DWORD oldProt = 0;
                            if (VirtualProtect(pGetProc, sizeof(uintptr_t), PAGE_EXECUTE_READWRITE, &oldProt))
                            {
                                *pGetProc = reinterpret_cast<uintptr_t>(&XignVtableGetProcStub);
                                DWORD dummy = 0;
                                VirtualProtect(pGetProc, sizeof(uintptr_t), oldProt, &dummy);
                                FlushInstructionCache(GetCurrentProcess(), pGetProc, sizeof(uintptr_t));
                                ++successCount;
                                Log(L"[HB]   [OK]   vtable[7] 0x%p -> XignVtableGetProcStub @0x%p",
                                    (void*)origFn, (void*)pGetProc);
                            }
                            else
                            {
                                Log(L"[HB]   [FAIL] vtable[7] VirtualProtect hatasi: %lu", GetLastError());
                            }
                        }
                    }
                }
            }
        }

        Log(L"[HB] ------------------------------------------------");
        Log(L"[HB] Patch sonucu: %d basarili (toplam %zu hedef)", successCount,
            (size_t)(sizeof(X3::TARGETS) / sizeof(X3::TARGETS[0])) + 2);

        m_installed = (successCount > 0);
        if (m_installed)
            Log(L"[HB] Heartbeat bypass AKTIF.");
        else
            Log(L"[HB] Heartbeat bypass BASARISIZ — hicbir patch uygulanamadi.");

        Log(L"[HB] ================================================");
        return m_patches;
    }

    void HeartbeatBypass::Uninstall()
    {
        if (!m_installed) return;

        for (const auto& rec : m_patches)
        {
            if (!rec.success || !rec.address) continue;

            auto* addr = reinterpret_cast<uint8_t*>(rec.address);
            DWORD oldProt = 0;
            if (VirtualProtect(addr, rec.patchLen, PAGE_EXECUTE_READWRITE, &oldProt))
            {
                SafeWriteBytes(addr, rec.original, rec.patchLen);
                DWORD dummy = 0;
                VirtualProtect(addr, rec.patchLen, oldProt, &dummy);
                FlushInstructionCache(GetCurrentProcess(), addr, rec.patchLen);
            }
        }

        m_installed = false;
        Log(L"[HB] Bypass kaldirildi (orijinal bytlar geri yuklendi).");
    }

